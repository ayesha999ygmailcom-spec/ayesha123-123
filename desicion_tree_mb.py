from sklearn.model_selection import train_test_split

# Split the dataset into 80% training and 20% testing
train_df, test_df = train_test_split(df, test_size=0.20, random_state=42)

print(f"Training set shape: {train_df.shape}")
print(f"Testing set shape:  {test_df.shape}")

from sklearn.compose import ColumnTransformer
from sklearn.preprocessing import OneHotEncoder, StandardScaler
from sklearn.ensemble import RandomForestClassifier
from sklearn.pipeline import Pipeline
from sklearn.metrics import classification_report, accuracy_score

# Define our features (X) and target (y)
feature_cols = ['hour_of_day', 'cash_type', 'Time_of_Day', 'Weekday', 'Month_name']
target_col = 'coffee_name'

X_train = train_df[feature_cols]
y_train = train_df[target_col]
X_test = test_df[feature_cols]
y_test = test_df[target_col]

# Preprocessing pipeline for categorical and numerical features
categorical_cols = ['cash_type', 'Time_of_Day', 'Weekday', 'Month_name']
numerical_cols = ['hour_of_day']

preprocessor = ColumnTransformer(
    transformers=[
        ('num', StandardScaler(), numerical_cols),
        ('cat', OneHotEncoder(handle_unknown='ignore'), categorical_cols)
    ]
)

# Create the full pipeline with a Random Forest Classifier
model_pipeline = Pipeline(steps=[
    ('preprocessor', preprocessor),
    ('classifier', RandomForestClassifier(n_estimators=100, random_state=42))
])

# Train the model
model_pipeline.fit(X_train, y_train)

# Make predictions on the test set
y_pred = model_pipeline.predict(X_test)

# Evaluate the model
accuracy = accuracy_score(y_test, y_pred)
print(f"Model Accuracy: {accuracy:.4f}\n")
print("--- Classification Report ---")
print(classification_report(y_test, y_pred))

from sklearn.metrics import confusion_matrix, ConfusionMatrixDisplay
import matplotlib.pyplot as plt
import seaborn as sns
import numpy as np

# Set seaborn theme style
sns.set_theme(style="whitegrid")

# Create subplots for confusion matrix and feature importances
fig, axes = plt.subplots(1, 2, figsize=(20, 8))

# 1. Confusion Matrix Heatmap
cm = confusion_matrix(y_test, y_pred, labels=model_pipeline.classes_)
disp = ConfusionMatrixDisplay(confusion_matrix=cm, display_labels=model_pipeline.classes_)
disp.plot(ax=axes[0], cmap='Blues', xticks_rotation=45)
axes[0].set_title('Confusion Matrix', fontsize=16)
axes[0].grid(False) # Disable grid lines for heatmap readability

# 2. Extract and Plot Feature Importances from Pipeline
# Extract feature names from preprocessor
ohe_feature_names = model_pipeline.named_steps['preprocessor'].named_transformers_['cat'].get_feature_names_out(categorical_cols)
all_feature_names = numerical_cols + list(ohe_feature_names)

importances = model_pipeline.named_steps['classifier'].feature_importances_

# Sort feature importances in descending order
indices = np.argsort(importances)[::-1]
top_n = min(15, len(all_feature_names)) # Show top 15 features

sns.barplot(
    x=[importances[i] for i in indices[:top_n]],
    y=[all_feature_names[i] for i in indices[:top_n]],
    ax=axes[1],
    palette='viridis'
)
axes[1].set_title(f'Top {top_n} Feature Importances', fontsize=16)
axes[1].set_xlabel('Relative Importance')

plt.tight_layout()
plt.show()

from sklearn.metrics import precision_recall_fscore_support
import pandas as pd

# Calculate metrics per class
precision, recall, f1, support = precision_recall_fscore_support(y_test, y_pred, labels=model_pipeline.classes_)

# Calculate per-class accuracy (True Positives / Actual Support for that class)
class_accuracies = []
for i, drink in enumerate(model_pipeline.classes_):
    tp = cm[i, i]
    total_actual = support[i]
    class_acc = tp / total_actual if total_actual > 0 else 0
    class_accuracies.append(class_acc)

# Create a summary DataFrame for all unique drinks in the dataset
metrics_df = pd.DataFrame({
    'Drink Label': model_pipeline.classes_,
    'Precision': precision,
    'Recall (Sensitivity)': recall,
    'F1-Score': f1,
    'Label Accuracy': class_accuracies,
    'Sample Support': support
})

# Format the scores as percentages
formatted_df = metrics_df.style.format({
    'Precision': '{:.2%}',
    'Recall (Sensitivity)': '{:.2%}',
    'F1-Score': '{:.2%}',
    'Label Accuracy': '{:.2%}'
})

display(formatted_df)

